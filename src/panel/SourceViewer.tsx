import { useEffect, useRef, useState } from 'react';
import type { Citation, Fragment, SlideDigest } from '../../shared/types';
import { api } from '../api';
import { Md } from '../Md';

type SlideInfo = { image: string; page: number; lectureNumber: number; lectureTitle: string; digest: SlideDigest | null; text: string };

export function SourceViewer({ citation, onClose }: { citation: Citation; onClose: () => void }) {
  const [slide, setSlide] = useState<SlideInfo | null>(null);
  const [frag, setFrag] = useState<(Fragment & { slide: { page: number; title: string } | null }) | null>(null);
  const [error, setError] = useState<string | null>(null);
  const close = useRef(onClose);
  close.current = onClose;
  useEffect(() => {
    const onKey = (e: KeyboardEvent) => e.key === 'Escape' && close.current();
    window.addEventListener('keydown', onKey, true);
    return () => window.removeEventListener('keydown', onKey, true);
  }, []);
  useEffect(() => {
    setSlide(null);
    setFrag(null);
    setError(null);
    // An entry citation shows the slide it lives on: what the classmates' notes were about.
    if (citation.kind === 'slide') api(`/api/slides/${citation.slideId}`).then(setSlide).catch((e) => setError(e.message));
    else if (citation.kind === 'entry') api(`/api/slides/${citation.slideId}`).then(setSlide).catch((e) => setError(e.message));
    else api(`/api/fragments/${citation.fragmentId}`).then(setFrag).catch((e) => setError(e.message));
  }, [citation]);
  return (
    <div className="modal-backdrop" onClick={onClose}>
      <div className="modal source" onClick={(e) => e.stopPropagation()} role="dialog" aria-label="Source">
        <button className="icon-btn small close" onClick={onClose} aria-label="Close">
          ×
        </button>
        {error && <div className="error-box">{error}</div>}
        {slide && (
          <>
            <div className="source-kind official">Official course slide</div>
            <h3>
              Lecture {slide.lectureNumber} · {slide.lectureTitle} — slide {slide.page}
            </h3>
            <img className="source-img" src={slide.image} alt={`Slide ${slide.page}`} />
            {slide.digest && (
              <div className="digest">
                <b>{slide.digest.title}</b>
                <Md text={slide.digest.summary} className="small" />
                <span className="muted small">Summary generated by AI from the slide for search and prompts.</span>
              </div>
            )}
          </>
        )}
        {frag && (
          <>
            <div className="source-kind peer">A classmate’s note</div>
            <h3>Notes{frag.slide ? ` on slide ${frag.slide.page}` : ''}</h3>
            <img className="source-img crop" src={`/api/fragments/${frag.id}/crop.png`} alt="Original handwriting" />
            <div className="digest">
              <span className="muted small">Transcribed by AI</span>
              <Md text={frag.text} />
            </div>
          </>
        )}
        {!slide && !frag && !error && <p className="muted">Loading source…</p>}
      </div>
    </div>
  );
}
